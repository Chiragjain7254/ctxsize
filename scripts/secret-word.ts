// Predicts, from ctxsize's own output, which secret fruits each agent knows in
// examples/secret-word, and writes (or checks) the table in docs/VERIFY.md.
// Run: npm run verify:gen
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { analyze } from '../src/core/analyze.ts';
import { walkFiles } from '../src/core/fs.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const EXAMPLE_DIR = path.resolve(HERE, '..', 'examples', 'secret-word');
export const VERIFY_MD = path.resolve(HERE, '..', 'docs', 'VERIFY.md');
export const START =
  '<!-- predictions:start (generated by npm run verify:gen, do not edit by hand) -->';
export const END = '<!-- predictions:end -->';

type Kind = 'main' | 'skill-description' | 'skill-body';
interface Fruit {
  word: string;
  file: string;
  kind: Kind;
}

export interface Prediction {
  agent: string;
  label: string;
  startup: string[];
  onDemand: string[];
  never: string[];
}

/** Every fruit in the example, found by its "Secret fruit ...: WORD" line. */
export function readFruits(dir: string): Fruit[] {
  const found: Fruit[] = [];
  for (const abs of walkFiles(dir, { gitignore: false })) {
    if (path.basename(abs) === '.ctxsizeignore') continue;
    const rel = path.relative(dir, abs).split(path.sep).join('/');
    for (const line of readFileSync(abs, 'utf8').split(/\r?\n/)) {
      const m = /Secret fruit( in the skill (description|body))?: ([A-Z]+)/.exec(line);
      if (!m) continue;
      const kind: Kind = m[2] ? (`skill-${m[2]}` as Kind) : 'main';
      found.push({ word: m[3] as string, file: rel, kind });
    }
  }
  return found;
}

export async function predict(dir = EXAMPLE_DIR): Promise<Prediction[]> {
  // Analyse a copy with a .git folder, so the example is its own repo root.
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'ctxsize-secret-'));
  try {
    cpSync(dir, tmp, { recursive: true });
    mkdirSync(path.join(tmp, '.git'));
    const fruits = readFruits(dir);
    const report = await analyze({ cwd: tmp, checks: false });
    return report.agents.map((a) => {
      const startup = new Set<string>();
      const onDemand = new Set<string>();
      for (const item of a.items) {
        if (item.load === 'ignored') continue;
        for (const f of fruits.filter((x) => x.file === item.path)) {
          if (f.kind === 'skill-body') onDemand.add(f.word);
          else (item.load === 'startup' ? startup : onDemand).add(f.word);
        }
      }
      const never = fruits.map((f) => f.word).filter((w) => !startup.has(w) && !onDemand.has(w));
      const sorted = (s: Iterable<string>): string[] => [...s].sort();
      return {
        agent: a.agent,
        label: a.label,
        startup: sorted(startup),
        onDemand: sorted(onDemand),
        never: sorted(never),
      };
    });
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

const cell = (words: string[]): string => (words.length ? words.join(', ') : 'none');

export function renderTable(
  predictions: Prediction[],
  kept: Map<string, [string, string]> = new Map(),
): string {
  const rows = predictions.map((p) => {
    const [observed, match] = kept.get(p.label) ?? ['not yet tested', '-'];
    return `| ${p.label} | ${cell(p.startup)} | ${cell(p.onDemand)} | ${cell(p.never)} | ${observed} | ${match} |`;
  });
  return [
    '| Agent | Fruits predicted at startup | Fruits only on demand | Fruits it should NOT know | Observed (date, agent version) | Match? |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
}

/** The table currently in VERIFY.md, as label -> cells. */
export function parseTable(md: string): Map<string, string[]> {
  const start = md.indexOf(START);
  const end = md.indexOf(END);
  const rows = new Map<string, string[]>();
  if (start < 0 || end < 0) return rows;
  for (const line of md.slice(start + START.length, end).split('\n')) {
    if (!line.startsWith('|') || line.startsWith('| Agent') || line.startsWith('| ---')) continue;
    const cells = line
      .split('|')
      .slice(1, -1)
      .map((c) => c.trim());
    rows.set(cells[0] as string, cells);
  }
  return rows;
}

async function main(): Promise<void> {
  const md = existsSync(VERIFY_MD) ? readFileSync(VERIFY_MD, 'utf8') : '';
  const kept = new Map<string, [string, string]>();
  for (const [label, cells] of parseTable(md))
    kept.set(label, [cells[4] ?? 'not yet tested', cells[5] ?? '-']);
  const table = `${START}\n${renderTable(await predict(), kept)}\n${END}`;
  const start = md.indexOf(START);
  const end = md.indexOf(END);
  if (start < 0 || end < 0) throw new Error(`${VERIFY_MD} has no predictions markers`);
  writeFileSync(VERIFY_MD, md.slice(0, start) + table + md.slice(end + END.length));
  console.log(`updated ${path.relative(process.cwd(), VERIFY_MD)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await main();
